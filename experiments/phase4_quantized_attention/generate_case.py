#!/usr/bin/env python3
"""Generate one deterministic Phase 4 case header for the target benchmark."""

from __future__ import annotations

import argparse
import struct
from pathlib import Path
from typing import Iterable

import numpy as np

from attention_model import SEED, run_case


def f32_bits(value: float | np.floating) -> int:
    return struct.unpack("<I", struct.pack("<f", float(np.float32(value))))[0]


def u32_array(name: str, values: Iterable[float | np.floating]) -> str:
    bits = [f"0x{f32_bits(value):08x}u" for value in values]
    lines = [f"static const uint32_t {name}[{len(bits)}] = {{"]
    for offset in range(0, len(bits), 6):
        lines.append("    " + ", ".join(bits[offset : offset + 6]) + ",")
    lines.append("};")
    return "\n".join(lines)


def i8_array(name: str, values: Iterable[int]) -> str:
    values = [int(value) for value in values]
    lines = [f"static const int8_t {name}[{len(values)}] = {{"]
    for offset in range(0, len(values), 24):
        lines.append("    " + ", ".join(str(value) for value in values[offset : offset + 24]) + ",")
    lines.append("};")
    return "\n".join(lines)


def flatten_float(array: np.ndarray) -> list[float]:
    return [float(value) for value in np.asarray(array, dtype=np.float32).ravel()]


def generate_header(n: int, d: int, seed: int) -> str:
    data = run_case(n, d, seed)
    wq = [np.asarray(value, dtype=np.int8) for value in data["wq"]]
    q_fp = np.asarray(data["q_fp"], dtype=np.float32)
    k_fp = np.asarray(data["k_fp"], dtype=np.float32)
    v_fp = np.asarray(data["v_fp"], dtype=np.float32)
    text = [
        "/* Generated by experiments/phase4_quantized_attention/generate_case.py. */",
        "#pragma once",
        "#include <stdint.h>",
        f"#define PHASE4_CASE_N {n}u",
        f"#define PHASE4_CASE_D {d}u",
        f"#define PHASE4_CASE_SEED {seed}u",
        "",
        u32_array("phase4_x_bits", flatten_float(np.asarray(data["x"]))),
        i8_array("phase4_wq_q", wq[0].ravel()),
        i8_array("phase4_wk_q", wq[1].ravel()),
        i8_array("phase4_wv_q", wq[2].ravel()),
        u32_array("phase4_q_scale_bits", [float(data["s"][0])]),
        u32_array("phase4_k_scale_bits", [float(data["s"][1])]),
        u32_array("phase4_v_scale_bits", [float(data["s"][2])]),
        u32_array("phase4_x_scale_bits", [float(data["sx"])]),
        u32_array("phase4_swq_bits", [float(data["sw"][0])]),
        u32_array("phase4_swk_bits", [float(data["sw"][1])]),
        u32_array("phase4_swv_bits", [float(data["sw"][2])]),
        u32_array("phase4_score_scale_bits", [float(data["score_scale"])]),
        "",
        # FP32 linear goldens are useful for the target-side checkpoint.
        u32_array("phase4_q_ref_bits", flatten_float(q_fp)),
        u32_array("phase4_k_ref_bits", flatten_float(k_fp)),
        u32_array("phase4_v_ref_bits", flatten_float(v_fp)),
        # The device score buffer is key-major [key][query]. Keep the
        # reference in that same layout so target-side score metrics do not
        # silently compare against the transposed tensor.
        u32_array(
            "phase4_ref_score_key_major_bits",
            flatten_float(np.asarray(data["score_ref"]).T),
        ),
        u32_array("phase4_ref_prob_bits", flatten_float(data["p_ref"])),
        u32_array("phase4_ref_output_bits", flatten_float(data["o_ref"])),
        # Proposed-path goldens validate the explicit-P Mixed integration.
        u32_array("phase4_mixed_prob_bits", flatten_float(data["p_mixed"])),
        u32_array("phase4_mixed_output_bits", flatten_float(data["o_mixed"])),
    ]
    return "\n\n".join(text) + "\n"


def main() -> int:
    parser = argparse.ArgumentParser()
    parser.add_argument("--n", type=int, required=True)
    parser.add_argument("--d", type=int, required=True)
    parser.add_argument("--seed", type=int, default=SEED)
    parser.add_argument("--output", type=Path, required=True)
    args = parser.parse_args()
    args.output.parent.mkdir(parents=True, exist_ok=True)
    args.output.write_text(generate_header(args.n, args.d, args.seed), encoding="utf-8")
    print(f"phase4-case generated N={args.n} D={args.d} seed={args.seed} output={args.output}")
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
