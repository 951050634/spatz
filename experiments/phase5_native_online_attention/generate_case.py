#!/usr/bin/env python3
"""Generate the small deterministic Q/K/V input for Phase 5.

The projections are deliberately prepared on the host.  Phase 5 measures the
native attention core after Q/K/V are resident, so no QKV linear work enters
the target timed region.  The source tensors are the same deterministic FP32
projection outputs used by the Phase 4 host model; this generator writes only
the tensors needed by the native path and its FP32 reference output.
"""

from __future__ import annotations

import argparse
import struct
import sys
from pathlib import Path
from typing import Iterable

import numpy as np


ROOT = Path(__file__).resolve().parents[2]
PHASE4 = ROOT / "experiments" / "phase4_quantized_attention"
if str(PHASE4) not in sys.path:
    sys.path.insert(0, str(PHASE4))
from attention_model import run_case  # noqa: E402


def f32_bits(value: float | np.floating) -> int:
    return struct.unpack("<I", struct.pack("<f", float(np.float32(value))))[0]


def u32_array(name: str, values: Iterable[float | np.floating]) -> str:
    bits = [f"0x{f32_bits(value):08x}u" for value in values]
    lines = [f"static const uint32_t {name}[{len(bits)}] = {{"]
    for offset in range(0, len(bits), 6):
        lines.append("    " + ", ".join(bits[offset : offset + 6]) + ",")
    lines.append("};")
    return "\n".join(lines)


def flatten(values: np.ndarray) -> list[float]:
    return [float(value) for value in np.asarray(values, dtype=np.float32).ravel()]


def generate_header(n: int, d: int, seed: int) -> str:
    data = run_case(n, d, seed)
    q = np.asarray(data["q_fp"], dtype=np.float32)
    k = np.asarray(data["k_fp"], dtype=np.float32)
    v = np.asarray(data["v_fp"], dtype=np.float32)
    reference = np.asarray(data["o_ref"], dtype=np.float32)
    return "\n\n".join(
        (
            "/* Generated by experiments/phase5_native_online_attention/generate_case.py. */",
            "#pragma once\n#include <stdint.h>",
            f"#define PHASE5_CASE_N {n}u\n#define PHASE5_CASE_D {d}u\n"
            f"#define PHASE5_CASE_SEED {seed}u\n#define PHASE5_TILE_KEYS 4u",
            u32_array("phase5_q_bits", flatten(q)),
            u32_array("phase5_k_bits", flatten(k)),
            u32_array("phase5_v_bits", flatten(v)),
            u32_array("phase5_reference_output_bits", flatten(reference)),
        )
    ) + "\n"


def main() -> int:
    parser = argparse.ArgumentParser()
    parser.add_argument("--n", type=int, required=True)
    parser.add_argument("--d", type=int, required=True)
    parser.add_argument("--seed", type=int, default=1)
    parser.add_argument("--output", type=Path, required=True)
    args = parser.parse_args()
    args.output.parent.mkdir(parents=True, exist_ok=True)
    args.output.write_text(
        generate_header(args.n, args.d, args.seed), encoding="utf-8"
    )
    print(
        f"phase5-case generated N={args.n} D={args.d} seed={args.seed} "
        f"output={args.output}"
    )
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
